#!/usr/bin/env node
// Writes VERIFICATION_LOG.md from data/verification.json and data/competitions.json (single source of truth).
const fs = require('fs'); const path = require('path'); const { ROOT } = require('./lib');
const V = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/verification.json'), 'utf8'));
const D = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/competitions.json'), 'utf8'));
const byId = Object.fromEntries(D.listings.map(l => [l.id, l]));
const q = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
let o = `# Verification log\n\nGenerated by \`tools/build_log.js\` from \`data/verification.json\`. Original pages read on ${V._meta.checkedOn} by session ${V._meta.session}; individually dated rechecks are labelled below.\n\n${V._meta.method}\n\n`;
o += `Levels: **verified** — ${V._meta.levels.verified} **partial** — ${V._meta.levels.partial} **contradicted** — ${V._meta.levels.contradicted}\n\n`;
o += `Unlisted rows (${D.listings.filter(l => l.verificationLevel === 'unverified').length}) were not read and are blank / unverified.\n\n`;
for (const [id, e] of Object.entries(V.entries)) {
  const l = byId[id];
  o += `## ${l.name} (\`${id}\`) — ${e.level}\n\n- Official page read (${e.checkedOn || V._meta.checkedOn}): [${q(e.sourceLabel)}](${e.sourceUrl})\n`;
  for (const [k, lab] of [['freeEntry', 'Free entry'], ['prize', 'Prize'], ['eligibility', 'Eligibility'], ['dates', 'Dates'], ['status', 'Status']]) o += `- ${lab}: ${e[k] ? q(e[k]) : '_blank — not confirmed_'}\n`;
  (e.notes || []).forEach(n => o += `- Note: ${q(n)}\n`);
  (e.discrepancies || []).forEach(d => o += `- **Discrepancy (${q(d.field)})** — ledger: ${q(d.upstream)}; official: ${q(d.official)}\n`);
  o += '\n';
}
fs.writeFileSync(path.join(ROOT, 'VERIFICATION_LOG.md'), o);
console.log('VERIFICATION_LOG.md written');
